#!/usr/bin/env python3
"""Generates lib/src/charset_tables.dart from Python's codecs.

Single-byte Windows code pages (upper half) and the double-byte cp932
(Shift_JIS) and cp949 (EUC-KR/UHC) tables. Undefined slots map to U+FFFD.
Run: python3 -I tool/gen_charset_tables.py > lib/src/charset_tables.dart
"""
import unicodedata

SINGLE = ['cp874', 'cp1250', 'cp1251', 'cp1252', 'cp1253', 'cp1254', 'cp1255', 'cp1256', 'cp1257', 'cp1258']


def lit(chars):
    out = []
    for ch in chars:
        o = ord(ch)
        if ch in "\\'$":
            out.append('\\' + ch)
        elif o < 0x20 or 0x7F <= o <= 0x9F or unicodedata.category(ch) in ('Cc', 'Cf', 'Co', 'Cs', 'Zl', 'Zp', 'Mn', 'Me', 'Cn'):
            out.append('\\u{%x}' % o)
        else:
            out.append(ch)
    return "'" + ''.join(out) + "'"


def dec(codec, b):
    try:
        ch = b.decode(codec)
    except UnicodeDecodeError:
        return '�'
    if len(ch) != 1 or 0xE000 <= ord(ch) <= 0xF8FF:
        return '�'
    return ch


def double(codec, leads, trails):
    rows = []
    for lead in leads:
        rows.append(lit(dec(codec, bytes([lead, t])) for t in trails))
    return rows


print('// GENERATED by tool/gen_charset_tables.py. Do not edit.')
print('// ignore_for_file: prefer_single_quotes')
print()
print('/// Upper halves (0x80-0xFF) of single-byte code pages, 128 chars each.')
print('const Map<String, String> singleByteTables = {')
for c in SINGLE:
    print("  '%s': %s," % (c.replace('cp', 'windows-'), lit(dec(c, bytes([b])) for b in range(0x80, 0x100))))
print('};')
print()
print('/// cp932 rows for lead bytes 0x81-0x9F then 0xE0-0xFC; trails 0x40-0xFC.')
print('const List<String> cp932Rows = [')
for r in double('cp932', list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD)), range(0x40, 0xFD)):
    print('  %s,' % r)
print('];')
print()
print('/// cp949 rows for lead bytes 0x81-0xFE; trails 0x41-0xFE.')
print('const List<String> cp949Rows = [')
for r in double('cp949', range(0x81, 0xFF), range(0x41, 0xFF)):
    print('  %s,' % r)
print('];')
